const html = document.documentElement;
const toggle = document.getElementById("langToggle");
const EN = {}; // filled from the page on first switch

function applyLang(lang) {
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const k = el.dataset.i18n;
    if (!(k in EN)) EN[k] = el.textContent;
    el.textContent = lang === "ar" ? (AR[k] ?? EN[k]) : EN[k];
  });
  document.querySelectorAll("[data-i18n-html]").forEach(el => {
    const k = el.dataset.i18nHtml;
    if (!(k in EN)) EN[k] = el.innerHTML;
    el.innerHTML = lang === "ar" ? (AR[k] ?? EN[k]) : EN[k];
  });
  html.lang = lang;
  html.dir = lang === "ar" ? "rtl" : "ltr";
  toggle.textContent = lang === "ar" ? "English" : "عربي";
  try { localStorage.setItem("lang", lang); } catch (e) {}
}

toggle.addEventListener("click", () => applyLang(html.lang === "ar" ? "en" : "ar"));
try { if (localStorage.getItem("lang") === "ar") applyLang("ar"); } catch (e) {}

// ---------- Mobile menu ----------
const burger = document.getElementById("burger");
const links = document.getElementById("navLinks");
burger.addEventListener("click", () => {
  const open = links.classList.toggle("is-open");
  burger.setAttribute("aria-expanded", open);
});
links.querySelectorAll("a").forEach(a => a.addEventListener("click", () => {
  links.classList.remove("is-open");
  burger.setAttribute("aria-expanded", "false");
}));

// ---------- Logo = Home: already on the homepage → smooth scroll to top ----------
document.getElementById("brandLink").addEventListener("click", e => {
  const onHome = /\/(index\.html)?$/.test(location.pathname);
  if (!onHome) return; // other pages: normal link to the homepage
  e.preventDefault();
  links.classList.remove("is-open");
  burger.setAttribute("aria-expanded", "false");
  history.replaceState(null, "", location.pathname);
  window.scrollTo({ top: 0, behavior: matchMedia("(prefers-reduced-motion: reduce)").matches ? "auto" : "smooth" });
});

// ---------- Sticky nav border ----------
