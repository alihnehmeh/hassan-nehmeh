// ---------- Hide photo placeholders once a real image exists ----------
document.querySelectorAll(".photo").forEach(el => {
  const m = /url\(['"]?(.*?)['"]?\)/.exec(el.style.getPropertyValue("--img"));
  if (!m) return;
  const img = new Image();
  img.onload = () => el.classList.add("has-img");
  img.src = m[1];
});

// ---------- Reveal on scroll ----------
const io = new IntersectionObserver(entries => {
  entries.forEach(e => { if (e.isIntersecting) { e.target.classList.add("is-visible"); io.unobserve(e.target); } });
}, { threshold: .12 });
document.querySelectorAll(".card, .step, .tile, .quote, .loc, .section__head, .about__copy, .about__media").forEach(el => {
  el.classList.add("reveal");
  io.observe(el);
});

